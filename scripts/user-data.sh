#!/bin/bash
# ==============================================================================
# 파일 개요: EC2 User-Data 부트스트랩 스크립트 (scripts/user-data.sh)
# ------------------------------------------------------------------------------
# 1. 목적:
#    - EC2 인스턴스 최초 프로비저닝 시 OS 부팅 과정에서 루트(root) 권한으로 1회 자동 실행.
#    - Nginx 웹 서버를 자동으로 설치 및 활성화.
#    - 외부 접속 검증을 위한 헬스체크 엔드포인트(/health) 및 기본 웹 페이지 구성.
# 2. 실행 환경 및 동작 특성:
#    - OS: Ubuntu 22.04 LTS (x86_64)
#    - 실행 주체: cloud-init (root 권한)
#    - 실행 로그: /var/log/cloud-init-output.log 에 표준 출력(stdout) 및 표준 에러(stderr) 기록
# 3. 주요 구성 요소:
#    - Nginx 패키지 설치 (apt-get)
#    - 가상 호스트 설정 파일 재작성 (/etc/nginx/sites-available/default)
#    - 헬스체크(/health): HTTP 200 OK 및 평문 "OK" 반환
#    - 루트 경로(/): 기본 환영 HTML 응답
#    - Nginx 설정 검증(nginx -t) 및 서비스 등록/시작(systemctl)
# ==============================================================================

# [안전 설정]
# set -e: 스크립트 실행 중 어느 한 명령어라도 0이 아닌 종료 코드(오류)를 반환하면 즉시 실행을 중단.
# 이를 통해 패키지 설치 실패나 설정 오류가 발생했을 때 잘못된 상태로 계속 진행되는 것을 방지합니다.
set -e

# ==============================================================================
# 단계 1: 시스템 패키지 저장소 갱신 및 Nginx 웹 서버 설치
# ==============================================================================
# - apt-get update: Ubuntu 공식 패키지 미러 서버로부터 최신 패키지 메타데이터 색인 정보를 갱신합니다.
#   (-y 옵션: 모든 확인 질문에 자동으로 Yes로 응답하여 대화형 프롬프트 대기를 방지)
apt-get update -y

# - apt-get install: Nginx 웹 서버 패키지를 비대화형(non-interactive) 모드로 설치합니다.
apt-get install -y nginx

# ==============================================================================
# 단계 2: Nginx 기본 사이트(가상 호스트) 설정 파일 작성
# ==============================================================================
# - Here Document(<< 'NGINXCONF')를 사용하여 /etc/nginx/sites-available/default 파일을 새로 작성합니다.
#   작은따옴표('NGINXCONF')로 감싸 쉘 변수 치환을 방지하고 순수 텍스트 그대로 파일에 기록합니다.
cat > /etc/nginx/sites-available/default << 'NGINXCONF'
server {
    # IPv4 포트 80에서 기본 서버(default_server)로 수신 대기
    listen 80 default_server;
    # IPv6 포트 80에서도 기본 서버로 수신 대기
    listen [::]:80 default_server;

    # --------------------------------------------------------------------------
    # 헬스체크 엔드포인트: /health
    # --------------------------------------------------------------------------
    # - 외부 접속 검증(방식 B: GET /health) 및 향후 로드밸런서(ALB)의 상태 검사용.
    # - 백엔드 WAS(Node.js, Python 등) 없이 Nginx 단독으로 200 상태코드와 "OK" 본문을 즉시 응답.
    # - Content-Type을 text/plain으로 명시하여 클라이언트가 평문 텍스트로 인식하도록 설정.
    location /health {
        add_header Content-Type text/plain;
        return 200 'OK';
    }

    # --------------------------------------------------------------------------
    # 기본 루트 경로: /
    # --------------------------------------------------------------------------
    # - 외부 접속 검증(방식 A: 브라우저 HTTP 접속) 시 화면에 렌더링될 환영 웹 페이지.
    # - Content-Type을 text/html로 지정하여 브라우저에서 HTML 문서로 렌더링되도록 처리.
    location / {
        add_header Content-Type text/html;
        return 200 '<html><body><h1>Hello Cloud &mdash; b6-1</h1><p>codyssey-b6-1 | Jack B.</p></body></html>';
    }
}
NGINXCONF

# ==============================================================================
# 단계 3: Nginx 설정 유효성 검사 및 서비스 재시작
# ==============================================================================
# - nginx -t: 작성된 설정 파일의 문법적 오류(Syntax Error)를 사전에 테스트합니다.
#   오류가 있다면 위에서 설정한 set -e에 의해 스크립트가 즉시 중단되어 비정상 기동을 방지합니다.
nginx -t

# - systemctl restart nginx: 새로운 설정 파일을 적용하기 위해 Nginx 데몬 프로세스를 재시작합니다.
systemctl restart nginx

# - systemctl enable nginx: 인스턴스가 재부팅되더라도 Nginx 데몬이 자동으로 시작되도록 systemd 서비스로 등록합니다.
systemctl enable nginx

# 스크립트 종료 (성공 시 정상 종료 코드 0 반환)
